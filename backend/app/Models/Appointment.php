<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Concerns\HasUlids;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;

// APPOINTMENTS (M6) — see the create_appointments_table migration. The bigint id stays internal; routes bind and
// resources expose the ULID public_id (CONTRACTS.md §1). Status changes happen only through AppointmentService's
// named commands, never through a generic update.
class Appointment extends Model
{
    use HasUlids;

    public const ACTIVE_STATUSES = ['Pending', 'Confirmed', 'Checked In', 'In Treatment'];

    public const TERMINAL_STATUSES = ['Completed', 'Cancelled', 'No-show'];

    // timestamptz columns: always write an explicit offset so the database session time zone never matters.
    protected $dateFormat = 'Y-m-d H:i:sP';

    // appointment_code is generated by PostgreSQL (column default) and immutable; the application never writes it.
    protected $guarded = ['id', 'public_id', 'appointment_code'];

    protected function casts(): array
    {
        return [
            'starts_at' => 'immutable_datetime',
            'ends_at' => 'immutable_datetime',
            'cancelled_at' => 'immutable_datetime',
            'booking_hold_expires_at' => 'immutable_datetime',
            'booking_paid_at' => 'immutable_datetime',
            'booking_refunded_at' => 'immutable_datetime',
            'booking_fee_php' => 'decimal:2',
            'duration_minutes' => 'integer',
            'revision' => 'integer',
        ];
    }

    /** Display outcome for the cancelled booking, separate from its stored payment status. */
    public function cancellationRefund(): ?array
    {
        if ($this->status !== 'Cancelled') {
            return null;
        }

        return match ($this->booking_payment_status) {
            'refunded' => $this->booking_refunded_at
                ? ['status' => 'refunded', 'message' => 'Your booking refund was confirmed.']
                : ['status' => 'unconfirmed', 'message' => 'The booking refund could not be verified. Contact the clinic with your appointment reference.'],
            'paid', 'partially_refunded' => ['status' => 'unconfirmed', 'message' => 'The booking refund is unconfirmed. Contact the clinic with your appointment reference.'],
            'forfeited' => ['status' => 'withheld', 'message' => 'No automatic refund was issued. Contact the clinic to review your booking payment.'],
            default => null,
        };
    }

    public function uniqueIds(): array
    {
        return ['public_id'];
    }

    public function getRouteKeyName(): string
    {
        return 'public_id';
    }

    public function patient(): BelongsTo
    {
        return $this->belongsTo(Patient::class);
    }

    public function branch(): BelongsTo
    {
        return $this->belongsTo(Branch::class);
    }

    public function service(): BelongsTo
    {
        return $this->belongsTo(Service::class);
    }

    public function dentist(): BelongsTo
    {
        return $this->belongsTo(DentistProfile::class, 'dentist_profile_id');
    }

    /** The Visit opened by this appointment's Check-In (M8), if any — at most one (visits_one_per_appointment). */
    public function visit(): HasOne
    {
        return $this->hasOne(Visit::class);
    }

    public function history(): HasMany
    {
        return $this->hasMany(AppointmentHistory::class)->orderBy('id');
    }

    public function checkoutSessions(): HasMany
    {
        return $this->hasMany(PaymentCheckoutSession::class);
    }

    public function activeCheckoutSession(): HasOne
    {
        return $this->hasOne(PaymentCheckoutSession::class)->where('status', 'Open');
    }

    public function scopeActive(Builder $query): Builder
    {
        return $query->whereIn('status', self::ACTIVE_STATUSES);
    }

    /** The authorization read scope (AppointmentPolicy::view expressed as a query). */
    public function scopeVisibleTo(Builder $query, User $user): Builder
    {
        return match ($user->role->value) {
            'owner' => $query,
            'patient' => $query->whereIn('patient_id', \App\Services\Intake\Guardianship::patientIdsFor($user) ?: [0]),
            'staff' => $query->whereIn('branch_id', UserBranchScope::select('branch_id')->where('user_id', $user->id)),
            'dentist' => $query->whereHas('dentist', fn (Builder $q) => $q->where('person_id', $user->person_id)),
        };
    }
}
