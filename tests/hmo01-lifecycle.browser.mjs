import assert from 'node:assert/strict'

// Deferred browser fixture acceptance; synthetic API success is not authenticated server acceptance.
export async function runHmo01Lifecycle(page, base = 'http://127.0.0.1:5176') {
  await page.goto(`${base}/tests/fixtures/hmo01-lifecycle.html`)
  const membership = page.locator('.hmo-membership')
  await membership.locator('summary').click()
  await page.evaluate(() => { window.hmo01.holdLoad = true })
  const visits = page.getByLabel('Visit', { exact: true })
  await visits.selectOption('visit-a')
  await visits.selectOption('visit-b')
  await visits.selectOption('visit-a')
  await page.waitForFunction(() => window.hmo01.loads.length === 3)
  await page.evaluate(() => window.hmo01.loads[2].release())
  await membership.getByText(/PRIVATE-A/).waitFor()
  await page.evaluate(() => { window.hmo01.loads[0].release(); window.hmo01.loads[1].release(); window.hmo01.holdLoad = false })
  assert.equal(await membership.getByText(/PRIVATE-B/).count(), 0)
  const provider = page.getByLabel('Provider name', { exact: true })
  await provider.selectOption({ index: 1 })
  await page.getByLabel('Member number', { exact: true }).fill('SYNTHETIC-REPLACEMENT')
  await page.evaluate(() => { window.hmo01.holdCommand = true })
  await membership.getByRole('button', { name: 'Replace membership', exact: true }).click()
  await page.waitForFunction(() => window.hmo01.requests.length === 1 && window.hmo01.release)
  assert.equal(await visits.isDisabled(), true)
  assert.equal(await provider.isDisabled(), true)
  assert.equal(await page.getByLabel('Member number', { exact: true }).isDisabled(), true)
  await page.evaluate(() => { window.hmo01.holdCommand = false; window.hmo01.release() })
  await membership.getByText(/Active:.*SYNTHETIC-REPLACEMENT/).waitFor()
  await page.locator('.hmo-case-row').filter({ hasText: 'Synthetic Patient A' }).first().click()
  await page.getByRole('button', { name: 'Record Provider Response', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Record externally received provider response' })
  await dialog.getByLabel('Channel', { exact: true }).selectOption('Phone')
  await dialog.getByLabel('Provider outcome received', { exact: true }).selectOption('Rejected')
  await dialog.getByLabel('Response details / pasted source text', { exact: true }).fill('Synthetic externally received response')
  await page.evaluate(() => { window.hmo01.failCommand = true })
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await dialog.getByRole('alert').waitFor()
  assert.equal(await dialog.getByLabel('Response details / pasted source text', { exact: true }).inputValue(), 'Synthetic externally received response')
  await page.evaluate(() => { window.hmo01.failCommand = false; window.hmo01.failRefresh = true })
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await dialog.waitFor({ state: 'detached' })
  await page.getByRole('alert').filter({ hasText: /server confirmed this change/ }).waitFor()
  const requests = await page.evaluate(() => window.hmo01.requests.filter(r => r.path.endsWith('/response')))
  assert.equal(requests.length, 2)
  assert.equal(requests[0].key, requests[1].key)
  assert.equal(requests[0].body.expected_revision, 1)
  await page.evaluate(() => { window.hmo01.failRefresh = false })
  await page.getByRole('button', { name: 'Reload HMO view', exact: true }).click()
  await page.getByRole('button', { name: 'Record Provider Response', exact: true }).click()
  await page.evaluate(() => window.hmo01.bumpCase('case-a'))
  assert.equal(await page.getByRole('dialog').getByRole('button', { name: 'Save', exact: true }).isDisabled(), true)
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.evaluate(() => window.hmo01.setRole('owner'))
  assert.equal(await page.locator('.hmo-membership').count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Record Provider Response', exact: true }).count(), 0)
  for (const width of [390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
}
