import assert from 'node:assert/strict'

// Deferred controlled-browser acceptance. No real accounts, databases or delivery evidence.
export async function runHndUi01Handovers(page, base = 'http://127.0.0.1:5176') {
  const settleUI = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.goto(`${base}/tests/fixtures/hnd-ui-01-handovers.html`)
  await page.getByRole('button', { name: 'Open (Auto-accept)', exact: true }).waitFor()
  await page.evaluate(() => { window.hndUi01.holdList = true; window.hndUi01.setPatient('patient-b') })
  await page.waitForFunction(() => window.hndUi01.heldLists.length === 1)
  await page.evaluate(() => window.hndUi01.setPatient('patient-a'))
  await page.waitForFunction(() => window.hndUi01.heldLists.length === 2)
  await page.evaluate(() => { window.hndUi01.heldLists[1].release(); window.hndUi01.heldLists[0].release(); window.hndUi01.holdList = false; window.hndUi01.rejectAck = true })
  await page.getByRole('button', { name: 'Open (Auto-accept)', exact: true }).click()
  const detail = page.getByRole('dialog', { name: 'Handover: Synthetic Patient A', exact: true })
  await detail.getByRole('button', { name: 'Retry automatic acknowledgment', exact: true }).waitFor()
  assert.equal(await detail.getByText('PRIVATE NOTES B', { exact: true }).count(), 0)
  assert.equal(await page.evaluate(() => window.hndUi01.feedback.some(f => f.tone === 'success')), false)
  await page.evaluate(() => { window.hndUi01.rejectAck = false })
  await detail.getByRole('button', { name: 'Retry automatic acknowledgment', exact: true }).focus()
  await page.keyboard.press('Enter')
  await detail.getByRole('status').filter({ hasText: 'Handover acknowledged.' }).waitFor()
  await page.keyboard.press('Escape'); await detail.waitFor({ state: 'detached' })
  assert.equal(await page.locator('.st-panel').evaluate(el => el.contains(document.activeElement)), true)

  await page.evaluate(() => { window.hndUi01.holdDocs = true })
  await page.getByRole('button', { name: 'Hand over care', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => window.hndUi01.heldDocs.length === 1)
  await page.evaluate(() => window.hndUi01.setPatient('patient-b'))
  await page.getByRole('button', { name: 'Hand over care', exact: true }).click()
  await page.waitForFunction(() => window.hndUi01.heldDocs.length === 2)
  await page.evaluate(() => { window.hndUi01.heldDocs[1].release(); window.hndUi01.heldDocs[0].release(); window.hndUi01.holdDocs = false })
  const form = page.getByRole('form', { name: 'Create Patient handover' })
  await form.getByLabel('From branch', { exact: true }).selectOption('b1')
  await form.getByLabel('To branch', { exact: true }).selectOption('b2')
  assert.equal(await form.getByText('PRIVATE TITLE A', { exact: true }).count(), 0)
  await form.getByLabel('Summary', { exact: true }).fill('Synthetic Patient B draft')
  await page.evaluate(() => { window.hndUi01.rejectCreate = true })
  await form.getByRole('button', { name: 'Send handover', exact: true }).click()
  await form.getByRole('alert').waitFor()
  assert.equal(await form.getByLabel('Summary', { exact: true }).inputValue(), 'Synthetic Patient B draft')
  await page.evaluate(() => { window.hndUi01.rejectCreate = false; window.hndUi01.holdMutation = true })
  await form.getByRole('button', { name: 'Send handover', exact: true }).click()
  await page.waitForFunction(() => window.hndUi01.release)
  assert.equal(await form.getByLabel('Summary', { exact: true }).isDisabled(), true)
  await page.evaluate(() => window.hndUi01.setPatient('patient-a'))
  await page.getByRole('button', { name: 'Hand over care', exact: true }).click()
  await page.getByLabel('Summary', { exact: true }).fill('New Patient A draft')
  const successBefore = await page.evaluate(() => window.hndUi01.feedback.length)
  await page.evaluate(() => { window.hndUi01.holdMutation = false; window.hndUi01.release() })
  await settleUI()
  assert.equal(await page.getByLabel('Summary', { exact: true }).inputValue(), 'New Patient A draft')
  assert.equal(await page.evaluate(() => window.hndUi01.feedback.length), successBefore)
  await form.getByLabel('From branch', { exact: true }).selectOption('b1')
  await form.getByLabel('To branch', { exact: true }).selectOption('b2')
  await form.getByRole('button', { name: 'Send handover', exact: true }).click()
  await page.getByRole('button', { name: 'Hand over care', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.hndUi01.feedback.at(-1).message), 'Handover recorded.')
  assert.equal(await page.evaluate(() => window.hndUi01.feedback.some(f => /receiving team was told|delivered/.test(f.message))), false)
  await page.getByRole('button', { name: 'Hand over care', exact: true }).evaluate(el => {
    if (el !== document.activeElement) throw Error('Create-form focus did not return to its opener')
  })
  await page.evaluate(() => { window.hndUi01.failList = true; window.hndUi01.setRole('owner'); window.hndUi01.setMode('inbox') })
  await page.getByText('Patient handovers', { exact: true }).waitFor()
  await page.getByRole('alert').filter({ hasText: 'Synthetic inbox retrieval failure' }).waitFor()
  assert.equal(await page.getByText('No handovers yet.', { exact: true }).count(), 0)
  await page.evaluate(() => { window.hndUi01.failList = false })
  await page.getByRole('button', { name: 'Retry handovers', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByText('Synthetic Patient A · a', { exact: true }).waitFor()
  assert.equal(await page.getByText(/PRIVATE NOTES|PRIVATE TITLE|PRIVATE SUMMARY/).count(), 0)
  for (const width of [390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
}
